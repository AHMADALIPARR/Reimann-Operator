# Writes the pgfplots coordinate files used by paper/sovereign_rh_lock.tex from the
# repository's own data (same inputs as docs/plots/make_figures.sh).
# usage (from the repo root): sh paper/figures/make_pgf.sh build/ro
set -eu
RO=${1:-build/ro}
D=paper/figures
ORACLE=data/zeta_zeros_oracle.txt
HDR='% Generated by paper/figures/make_pgf.sh from the repository data; do not edit.'

# N(T) staircase of the oracle and the Riemann-von Mangoldt main term
awk -v hdr="$HDR" '{ t[++n] = $NF + 0 }
END {
  pi = atan2(0, -1); print hdr
  printf "\\addplot[const plot, color=primary, thick] coordinates {(0,0)"
  for (i = 1; i <= n; i++) printf "%s(%.4f,%d)", (i % 8 ? " " : "\n"), t[i], i
  printf " (850,%d)};\n", n
  printf "\\addplot[color=red!70!black, densely dashed, thick] coordinates {"
  for (v = 10; v <= 850; v += 10) { y = v/(2*pi)*log(v/(2*pi*exp(1))) + 7/8; if (y < 0) y = 0; printf "%s(%d,%.3f)", (v % 100 ? " " : "\n"), v, y }
  printf "};\n"
}' $ORACLE > $D/zeros_count.tex

# unfolded nearest-neighbour spacings: histogram (bin 0.15) and summary macros
awk -v hdr="$HDR" '{ t[++n] = $NF + 0 }
END {
  pi = atan2(0, -1); bw = 0.15; nb = 20; print hdr
  for (i = 1; i <= n; i++) x[i] = t[i]/(2*pi)*log(t[i]/(2*pi*exp(1))) + 7/8
  for (i = 1; i < n; i++) { s[i] = x[i+1] - x[i]; sum += s[i] }
  m = n - 1; mean = sum / m
  for (i = 1; i < n; i++) { q += (s[i]/mean - 1)^2; b = int(s[i]/mean/bw); if (b < nb) c[b]++ }
  printf "\\addplot[ybar interval, fill=primary!25, draw=primary] coordinates {"
  for (b = 0; b < nb; b++) printf "%s(%.2f,%.4f)", (b % 5 ? " " : "\n"), b*bw, c[b]/(m*bw)
  printf " (%.2f,0)};\n", nb*bw
  printf "\\def\\spacingcount{%d}\\def\\spacingmean{%.4f}\\def\\spacingstd{%.4f}\n", m, mean, sqrt(q/m)
}' $ORACLE > $D/spacing_hist.tex

# Berry-Keating eigenvalues (a = 1, b = 10, theta = 0) for n = 32, 64, 128 against the zeros up to 60
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
for n in 32 64 128; do
  "$RO" bk $n 1.0 10.0 0.0 > "$TMP/bk$n.json"
  "$RO" eigvalsh "$TMP/bk$n.json" > "$TMP/ev$n.json"
done
awk -v hdr="$HDR" -v tmax=60 '
FNR == 1 { r++ }
/^\[/ { gsub(/[][ ]/, ""); k = split($0, a, ","); for (i = 1; i <= k; i++) { v = a[i] + 0; if (v > 1e-9 && v <= tmax) val[r, ++cnt[r]] = v }; next }
{ v = $NF + 0; if (v <= tmax) val[r, ++cnt[r]] = v }
END {
  print hdr
  for (q = 1; q <= r; q++) {
    m = cnt[q]; for (i = 1; i <= m; i++) w[i] = val[q, i]
    for (i = 2; i <= m; i++) { v = w[i]; j = i - 1; while (j > 0 && w[j] > v) { w[j+1] = w[j]; j-- }; w[j+1] = v }
    prev = -1; d = 0
    printf "\\addplot[only marks, mark=|, mark size=5pt, thick, color=%s] coordinates {", (q == r ? "red!70!black" : "primary")
    for (i = 1; i <= m; i++) if (w[i] - prev > 1e-6 * (1 + w[i])) { d++; prev = w[i]; printf "%s(%.4f,%d)", (d % 8 ? " " : "\n"), w[i], r - q + 1 }
    printf "};\n"
  }
}' "$TMP/ev32.json" "$TMP/ev64.json" "$TMP/ev128.json" $ORACLE > $D/bk_barcode.tex
ls -l $D/*.tex
